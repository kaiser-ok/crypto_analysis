# --- 分析敘述自動生成 ---

def _generate_narrative(graph: FlowGraph) -> str:
    """依拓撲順序走訪 FlowGraph 的 edges，生成中文分析敘述。

    同一對 (from, to) 的多筆交易聚合為一段，避免重複敘述。
    """
    if not graph.edges:
        return "本案未追蹤到任何交易紀錄。"

    paragraphs = []

    # 聚合同一對 (from, to) 的邊：加總金額、取最早時間、計算筆數
    pair_agg: dict[tuple[str, str], dict] = {}
    for edge in graph.edges:
        key = (edge.from_address, edge.to_address)
        if key not in pair_agg:
            pair_agg[key] = {
                "total_amount": 0.0,
                "token": edge.token,
                "earliest_ts": edge.timestamp,
                "latest_ts": edge.timestamp,
                "tx_count": 0,
            }
        agg = pair_agg[key]
        agg["total_amount"] += edge.amount
        agg["tx_count"] += 1
        if edge.timestamp and (agg["earliest_ts"] == 0 or edge.timestamp < agg["earliest_ts"]):
            agg["earliest_ts"] = edge.timestamp
        if edge.timestamp and edge.timestamp > agg["latest_ts"]:
            agg["latest_ts"] = edge.timestamp

    # 按 from_node.layer → earliest_ts 排序
    sorted_pairs = sorted(pair_agg.items(), key=lambda item: (
        graph.nodes.get(item[0][0], FlowNode("", 0, "")).layer,
        item[1]["earliest_ts"],
    ))

    for (from_addr, to_addr), agg in sorted_pairs:
        from_node = graph.nodes.get(from_addr)
        to_node = graph.nodes.get(to_addr)
        if not from_node or not to_node:
            continue

        amount_str = _format_amount(agg["total_amount"], agg["token"])
        tx_count = agg["tx_count"]

        # 時間描述
        if agg["earliest_ts"] == agg["latest_ts"] or tx_count == 1:
            date_str = _ts_to_str(agg["earliest_ts"]) if agg["earliest_ts"] else "未知時間"
            time_desc = f"於 {date_str}"
        else:
            start_str = _ts_to_str(agg["earliest_ts"]) if agg["earliest_ts"] else "未知時間"
            end_str = _ts_to_str(agg["latest_ts"]) if agg["latest_ts"] else "未知時間"
            time_desc = f"於 {start_str} 至 {end_str} 期間"

        count_desc = f"（共 {tx_count} 筆交易）" if tx_count > 1 else ""

        line = (
            f"地址 {from_node.alias}（{_short_addr(from_addr)}）"
            f"{time_desc}將 {amount_str} 轉出至"
            f"地址 {to_node.alias}（{_short_addr(to_addr)}）{count_desc}"
        )

        if to_node.is_exchange:
            exchange_name = ", ".join(to_node.labels) if to_node.labels else "交易所"
            line += f"。經查地址 {to_node.alias} 為 {exchange_name} 之地址"

        wtype = WALLET_TYPE_LABELS.get(to_node.wallet_type, "")
        if wtype:
            line += f"（經研判為{wtype}）"

        line += "。"
        paragraphs.append(line)

    return "\n\n".join(paragraphs)


def _generate_association_text(graph: FlowGraph) -> list[str]:
    """依幣流圖判斷各錢包間的從屬與支配關係。"""
    lines = []

    # 建立邊的索引
    outgoing: dict[str, list[FlowEdge]] = {}
    for edge in graph.edges:
        outgoing.setdefault(edge.from_address, []).append(edge)

    for layer_idx in sorted(graph.layers.keys()):
        for addr in graph.layers[layer_idx]:
            node = graph.nodes.get(addr)
            if not node or node.is_exchange:
                continue

            out_edges = outgoing.get(addr, [])
            if not out_edges:
                continue

            targets = []
            for e in out_edges:
                to_node = graph.nodes.get(e.to_address)
                if to_node:
                    targets.append(to_node.alias)

            if targets:
                unique_targets = list(dict.fromkeys(targets))
                lines.append(
                    f"地址 {node.alias} 將資金轉出至 {'、'.join(unique_targets)}，"
                    f"研判 {node.alias} 與 {'、'.join(unique_targets)} 間具有資金從屬關係。"
                )

    return lines


