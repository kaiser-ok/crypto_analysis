"""交易所調閱用虛擬通貨幣流分析報告 HTML 生成器。

產出 A4 列印最佳化 HTML，結構對齊參考 PDF 範本：
封面、目錄+免責聲明、案件資訊、錢包概況、分析情形、結論及建議事項、名詞解釋。
"""

import os
from datetime import datetime

from flow_tracer import (
    FlowGraph, FlowNode, FlowEdge, CaseInfo, LAYER_LETTERS,
    classify_wallets, analyze_trx_gas,
)
from flow_report import (
    _esc, _short_addr, _ts_to_str, _ts_to_date, _format_amount,
    _tronscan_addr_link, _tronscan_tx_link, _generate_flow_svg,
)
from templates.disclaimer import EXCHANGE_REPORT_DISCLAIMER_ITEMS
from templates.glossary import EXCHANGE_REPORT_GLOSSARY_ITEMS


# --- 錢包角色中文名稱 ---

WALLET_TYPE_LABELS = {
    "relay": "中繼錢包",
    "profit": "獲利錢包",
    "mule": "車手錢包",
}


def _wallet_role_description(node: FlowNode, graph: FlowGraph) -> str:
    """根據節點屬性產生錢包角色描述。"""
    if node.is_exchange:
        name = ", ".join(node.labels) if node.labels else "交易所"
        return f"交易所地址（{name}）"
    if node.layer == 0:
        return "起始追蹤地址（被告/涉嫌人轉幣錢包）"
    if node.wallet_type == "relay":
        return "中繼錢包（用於中轉、分散資金）"
    if node.wallet_type == "profit":
        return "獲利錢包（向被害人發送假獲利）"
    return "犯嫌收款錢包"


# --- 報告生成主函式 ---

def generate_exchange_report(
    graph: FlowGraph,
    case_info: CaseInfo,
    output_path: str,
    trx_providers: dict[str, str] | None = None,
) -> str:
    """產生交易所調閱用虛擬通貨幣流分析報告 HTML。"""

    # 自動分類錢包
    classify_wallets(graph)

    now = datetime.now()
    roc_year = now.year - 1911
    report_date_roc = f"中華民國 {roc_year} 年 {now.month} 月 {now.day} 日"
    report_date = case_info.request_date or now.strftime("%Y年%m月%d日")

    # 收集所有交易序號
    tx_hashes = list(dict.fromkeys(e.tx_hash for e in graph.edges if e.tx_hash))

    # SVG 幣流圖
    svg_content = _generate_flow_svg(graph)

    # 組合 HTML
    html_content = _build_exchange_html(
        case_info=case_info,
        report_date=report_date,
        report_date_roc=report_date_roc,
        graph=graph,
        tx_hashes=tx_hashes,
        svg_content=svg_content,
        trx_providers=trx_providers or {},
    )

    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(html_content)

    return output_path


# --- HTML 組建 ---

def _build_exchange_html(
    case_info: CaseInfo,
    report_date: str,
    report_date_roc: str,
    graph: FlowGraph,
    tx_hashes: list[str],
    svg_content: str,
    trx_providers: dict[str, str],
) -> str:
    """組建完整交易所調閱報告 HTML。"""

    cover = _build_cover(case_info, report_date_roc)
    toc_disclaimer = _build_toc_and_disclaimer()
    sec1 = _build_section1_case_info(case_info, report_date, graph, tx_hashes)
    wallet_overview = _build_wallet_overview(graph)
    sec2 = _build_section2_analysis(graph, svg_content, trx_providers)
    sec3 = _build_section3_conclusion(graph, case_info, report_date)
    sec4 = _build_section4_glossary()

    return f"""<!DOCTYPE html>
<html lang="zh-TW">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>虛擬通貨幣流分析報告 — {_esc(case_info.case_number)}</title>
<style>
{_get_exchange_report_css()}
</style>
</head>
<body>
{cover}
{toc_disclaimer}
{sec1}
{wallet_overview}
{sec2}
{sec3}
{sec4}

<footer class="page-footer">
    <span class="footer-case">{_esc(case_info.case_number)}</span>
    <span class="footer-gen">Generated by crypto-acc-chk · MistTrack AML</span>
</footer>
</body>
</html>"""


